async (providedPage) => {
  const base = "http://127.0.0.1:38086";
  const browser = providedPage.context().browser();
  const adminContext = await browser.newContext();
  const userContext = await browser.newContext();
  const page = await adminContext.newPage();
  const userPage = await userContext.newPage();
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const requests = [];
  for (const context of [adminContext,userContext]) context.on("request", request => requests.push({url:request.url(),referrer:request.headers().referer}));
  try {
    await page.goto(base+"/login");
    await page.locator('[name="password"]').fill("d06-local-browser-only-password");
    await Promise.all([page.waitForURL(base+"/admin"),page.locator('button').click()]);
    const list = await page.request.get(base+"/api/admin/users");
    const csrf = (await list.json()).csrf;
    const headers = {Origin:base,"X-CSRF-Token":csrf};
    const groupResponse = await page.request.post(base+"/api/admin/groups/user",{headers,data:{name:"browser-"+Date.now(),node_group_ids:[]}});
    assert(groupResponse.status()===201,"group setup failed");
    const group = await groupResponse.json();
    const userResponse = await page.request.post(base+"/api/admin/users",{headers,data:{name:"browser-"+Date.now(),user_group_id:group.group_id,enabled:true,expires_at:"",quota_bytes:0}});
    assert(userResponse.status()===201,"user setup failed");
    const user = await userResponse.json();
    await page.goto(base+"/admin/users");
    await page.getByRole("link",{name:"私有链接管理"}).click();
    await page.locator(`input[name="user_ids"][value="${user.user_id}"]`).check();
    await Promise.all([page.waitForNavigation(),page.getByRole("button",{name:"显式创建 / 重置并一次性交付"}).click()]);
    const deliveries = await page.locator("[data-token-delivery]").evaluateAll(items=>items.map(item=>({...item.dataset})));
    const dash = deliveries.find(item=>item.kind==="dashboard").token;
    const sub = deliveries.find(item=>item.kind==="subscription").token;
    assert(dash && sub && dash!==sub,"independent token delivery missing");
    assert(await page.locator(".delivery-links a").count()===3,"one-time links did not render under CSP");
    const firstExpiry = await page.evaluate(id=>JSON.parse(sessionStorage.getItem(`panel-agent-token:${id}:subscription`)).expires,user.user_id);
    const reloadResponse = await page.goto(base+"/admin/user-links");
    assert(!(await reloadResponse.text()).includes(sub),"GET recovered token plaintext");
    assert(await page.locator(".cached-links a").count()===3,"same-tab cache missing");
    const nextExpiry = await page.evaluate(id=>JSON.parse(sessionStorage.getItem(`panel-agent-token:${id}:subscription`)).expires,user.user_id);
    assert(firstExpiry===nextExpiry,"reading cache extended TTL");
    await userPage.goto(base+"/u/"+dash);
    assert(await userPage.locator(".cached-links a").count()===0,"fresh browser recovered old subscription secret");
    assert((await userPage.locator("body").innerText()).includes("尚未启用"),"dashboard invented usage");
    assert((await userPage.locator("body").innerText()).includes("sing-box 1.14.3"),"unsupported client notice missing");
    await Promise.all([userPage.waitForNavigation(),userPage.getByRole("button",{name:"显式重置我的订阅 Token"}).click()]);
    const newSub = await userPage.locator('[data-token-delivery][data-kind="subscription"]').getAttribute("data-token");
    assert(newSub && newSub!==sub,"end-user reset failed");
    assert((await userPage.request.get(base+"/s/"+sub+"/uri")).status()===404,"old URL still valid");
    assert((await userPage.request.get(base+"/s/"+newSub+"/uri")).status()===200,"new URL failed");
    await page.goto(base+"/admin/user-links");
    assert(await page.locator(".cached-links a").count()===1,"stale generation retained old subscription");
    await userPage.evaluate(id=>{const k=`panel-agent-token:${id}:subscription`;const v=JSON.parse(sessionStorage.getItem(k));v.expires=Date.now()-1;sessionStorage.setItem(k,JSON.stringify(v));},user.user_id);
    await userPage.goto(base+"/u/"+dash);
    assert(await userPage.locator(".cached-links a").count()===0,"expired temporary secret displayed");
    assert(await userPage.evaluate(id=>sessionStorage.getItem(`panel-agent-token:${id}:subscription`),user.user_id)===null,"expired secret not purged");
    await page.getByRole("button",{name:"清除当前标签页临时保存的 Token"}).click();
    assert(await page.evaluate(()=>Object.keys(sessionStorage).filter(k=>k.startsWith("panel-agent-token:")).length)===0,"forget action left cache");
    assert(requests.every(r=>r.url.startsWith(base)),"third-party request from private pages");
    assert(requests.every(r=>!r.referrer),"private navigation sent Referer");
    return {passed:true,checks:["admin one-time delivery","fresh browser cannot recover subscription","explicit user reset","old URL invalid","generation and TTL cache expiry","forget cache","no third-party requests or Referer","unsupported sing-box notice"]};
  } finally { await userContext.close(); await adminContext.close(); }
}
